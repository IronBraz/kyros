/**
 * Bakes knowledge/public/*.md into server/lib/wiki.generated.ts at build time.
 *
 * The n8n version (SUB_Wiki_Loader) did `fs.readdirSync` at runtime on every single chat
 * message. On serverless that is both unreliable (the knowledge folder is not guaranteed to
 * be in the function bundle) and wasteful. Baking it into a module means the wiki is a plain
 * import: zero I/O, and the bundler guarantees it ships with the function.
 *
 * Consequence: editing the wiki now requires a commit + push, which triggers a redeploy.
 *
 * The output format is byte-for-byte what SUB_Wiki_Loader produced, so the model sees the
 * same prompt it saw under n8n:
 *     ### <filename>\n<raw contents>
 * joined by "\n\n---\n\n", files sorted alphabetically.
 *
 * Run via the `prebuild` npm lifecycle hook -- it fires automatically before `npm run build`.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const knowledgeDir = join(repoRoot, 'knowledge', 'public');
const outFile = join(repoRoot, 'server', 'lib', 'wiki.generated.ts');

const files = readdirSync(knowledgeDir)
  .filter((f) => f.endsWith('.md'))
  .sort();

if (files.length === 0) {
  console.error(`[generate-wiki] no .md files found in ${knowledgeDir}`);
  process.exit(1);
}

const content = files
  .map((f) => `### ${f}\n${readFileSync(join(knowledgeDir, f), 'utf8')}`)
  .join('\n\n---\n\n');

// Short content hash: the wiki "version" the admin panel displays. Changing any page
// changes it, which is exactly what /admin/wiki/reload needs to report.
const version = createHash('sha256').update(content).digest('hex').slice(0, 12);

const banner = `// AUTO-GENERATED by scripts/generate-wiki.ts -- do not edit, do not commit.
// Source: knowledge/public/*.md (${files.length} files)
// Regenerate with: npm run prebuild
`;

const module = `${banner}
export const WIKI_CONTENT = ${JSON.stringify(content)};
export const WIKI_VERSION = ${JSON.stringify(version)};
export const WIKI_FILE_COUNT = ${files.length};
export const WIKI_FILES: readonly string[] = ${JSON.stringify(files)};
export const WIKI_BUILT_AT = ${JSON.stringify(new Date().toISOString())};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, module, 'utf8');

console.log(
  `[generate-wiki] ${files.length} files -> ${outFile} ` +
    `(version ${version}, ${content.length} chars)`
);
